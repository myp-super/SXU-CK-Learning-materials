void LCD_Init(void)
{
    LCD_GPIO_Init();
    LCD_FSMC_Init();
    LCD_ILI9341_Init();
    LCD_Clear(WHITE);
}

void LCD_Clear(uint16_t color)
{
    uint32_t i, n = (uint32_t)LCD_W * LCD_H;
    LCD_SetWin(0, 0, LCD_W - 1, LCD_H - 1);
    for (i = 0; i < n; i++) LCD_DATA = color;
}

void LCD_ShowChar(uint16_t x, uint16_t y, uint8_t ch, uint8_t size, uint16_t color)
{
    uint8_t t, d, csize = (size / 8) * size;  /* 16→32 bytes */
    if (ch < ' ' || ch > '~') ch = ' ';
    ch -= ' ';

    LCD_SetWin(x, y, x + size / 2 - 1, y + size - 1);
    for (t = 0; t < csize; t++) {
        d = font_1608[ch][t / 2];  /* 每字节放2个像素 */
        for (uint8_t b = 0; b < 8; b++) {
            LCD_DATA = (d & 0x80) ? color : WHITE;
            d <<= 1;
        }
    }
}

void LCD_ShowString(uint16_t x, uint16_t y, uint16_t w, uint8_t size,
                    uint16_t color, uint8_t *str)
{
    uint16_t x0 = x;
    while (*str) {
        if (x > x0 + w - size / 2) { x = x0; y += size; }
        if (y > LCD_H - size) break;
        LCD_ShowChar(x, y, *str++, size, color);
        x += size / 2;
    }
}
