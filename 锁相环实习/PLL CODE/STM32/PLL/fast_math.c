#define TABLE_SIZE 256
#define TWO_PI_F 6.283185307f
#define INV_TWO_PI 0.159154943f

float fast_sin(float x)
{
    /* Normalize x to [0, 2*PI) */
    if (x < 0.0f) {
        while (x < 0.0f) x += TWO_PI_F;
    }
    while (x >= TWO_PI_F) {
        x -= TWO_PI_F;
    }

    /* Map to table index */
    float idx_f = x * (float)TABLE_SIZE * INV_TWO_PI;
    int idx = (int)idx_f;
    float frac = idx_f - (float)idx;

    /* Linear interpolation */
    return sin_table[idx] + frac * (sin_table[idx + 1] - sin_table[idx]);
}

float fast_cos(float x)
{
    /* cos(x) = sin(x + PI/2) */
    return fast_sin(x + 1.570796327f);
}
